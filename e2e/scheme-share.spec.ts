import { expect, test } from '@playwright/test'

test('step links and share link round trip', async ({ page, browser, baseURL }) => {
  const errors: string[] = []
  page.on('pageerror', (e) => errors.push(e.message))
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'], { origin: new URL(baseURL!).origin })
  await page.goto('./')
  await page.getByRole('button', { name: 'Schemes' }).click()
  await page.getByRole('button', { name: '+ New scheme' }).click()
  const ed = page.getByRole('region', { name: 'Scheme editor' })
  await ed.getByLabel('Scheme name').fill('Shared Blue')
  await ed.getByRole('button', { name: '+ Area' }).click()
  await ed.getByRole('button', { name: '+ Step' }).click()
  const step = ed.getByRole('listitem', { name: 'Step 1' })
  await step.getByLabel('Technique').fill('basecoat')
  await step.getByRole('combobox', { name: 'Paint' }).fill('macragge blue')
  await step.getByRole('option', { name: /Macragge Blue/ }).first().click()
  await step.getByRole('button', { name: '+ video / tutorial link' }).click()
  await step.getByLabel('Link URL').fill('https://www.youtube.com/watch?v=abc')
  await step.getByLabel('Link title').fill('Basecoat video')
  await step.getByRole('button', { name: '+ video / tutorial link' }).click()
  await ed.getByRole('button', { name: 'Save' }).click()
  await expect(ed.getByRole('button', { name: 'Saved' })).toBeVisible()
  await ed.getByRole('button', { name: '🔗 Share link' }).click()
  await expect(ed.getByRole('status')).toContainText('Link copied')
  const url = await page.evaluate(() => navigator.clipboard.readText())
  expect(url).toContain('#scheme=')

  const other = await browser.newPage()
  await other.goto(url)
  const banner = other.getByRole('region', { name: 'Shared scheme' })
  await expect(banner).toContainText('Shared Blue, 1 steps')
  await banner.getByRole('button', { name: 'Import scheme' }).click()
  await expect(banner).toHaveCount(0)
  expect(new URL(other.url()).hash).toBe('')
  const step2 = other.getByRole('region', { name: 'Scheme editor' }).getByRole('listitem', { name: 'Step 1' })
  await expect(step2.getByLabel('Link URL')).toHaveValue('https://www.youtube.com/watch?v=abc')
  await expect(step2.getByLabel('Link URL')).toHaveCount(1)
  await other.screenshot({ path: process.env.SHOT ?? 'test-results/share.png' })
  expect(errors).toEqual([])
})
